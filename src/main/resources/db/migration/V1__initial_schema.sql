    CONSTRAINT fk_master_menu_template_item__master_product FOREIGN KEY (master_product_id) REFERENCES master_product(id),
    CONSTRAINT uk_master_menu_template_item__template_product UNIQUE (master_template_id, master_product_id)
);

CREATE INDEX idx_master_menu_template_item__master_template_id ON master_menu_template_item (master_template_id);
CREATE INDEX idx_master_menu_template_item__master_product_id ON master_menu_template_item (master_product_id);
COMMENT ON TABLE master_menu_template_item IS 'Items in master menu templates';

