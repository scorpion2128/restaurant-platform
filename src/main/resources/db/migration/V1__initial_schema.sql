    CONSTRAINT ck_order_item__quantity_positive CHECK (quantity > 0),
    CONSTRAINT ck_order_item__unit_price_positive CHECK (unit_price >= 0),
    CONSTRAINT ck_order_item__subtotal_positive CHECK (subtotal >= 0)
