CREATE TABLE product (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id       BIGINT NOT NULL,
    master_product_id   BIGINT NOT NULL,
    price               NUMERIC(10,2) NOT NULL,
    available           BOOLEAN NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by          BIGINT,
    updated_by          BIGINT,

    CONSTRAINT fk_product__restaurant FOREIGN KEY (restaurant_id) REFERENCES restaurant(id),
    CONSTRAINT fk_product__master_product FOREIGN KEY (master_product_id) REFERENCES master_product(id),
    CONSTRAINT ck_product__price_positive CHECK (price >= 0),
    CONSTRAINT uk_product__restaurant_master_product UNIQUE (restaurant_id, master_product_id)
);

CREATE INDEX idx_product__restaurant_id ON product (restaurant_id);
CREATE INDEX idx_product__master_product_id ON product (master_product_id);
COMMENT ON TABLE product IS 'Restaurant-specific product data - only price and availability';
COMMENT ON COLUMN product.master_product_id IS 'REQUIRED: Link to master catalog for name/description';
COMMENT ON COLUMN product.price IS 'Restaurant-specific price (may differ from base_price)';
COMMENT ON COLUMN product.available IS 'Restaurant-specific availability';

