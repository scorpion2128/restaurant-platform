CREATE TABLE restaurant_table (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id   BIGINT NOT NULL,
    number          VARCHAR(20) NOT NULL,
    capacity        INTEGER NOT NULL,
    status          VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE',
    active          BOOLEAN NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by      BIGINT,
    updated_by      BIGINT,

    CONSTRAINT fk_restaurant_table__restaurant FOREIGN KEY (restaurant_id) REFERENCES restaurant(id),
    CONSTRAINT ck_restaurant_table__number_not_blank CHECK (length(trim(number)) > 0),
    CONSTRAINT ck_restaurant_table__capacity_positive CHECK (capacity > 0),
    CONSTRAINT ck_restaurant_table__status CHECK (status IN ('AVAILABLE', 'OCCUPIED', 'RESERVED', 'UNAVAILABLE')),
    CONSTRAINT uk_restaurant_table__restaurant_number UNIQUE (restaurant_id, number)
);

CREATE INDEX idx_restaurant_table__restaurant_id ON restaurant_table (restaurant_id);
COMMENT ON TABLE restaurant_table IS 'Tables per restaurant';

-- ============================================
-- ORDER MANAGEMENT
-- ============================================

CREATE TABLE order_table (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id   BIGINT NOT NULL,
    waiter_id       BIGINT NOT NULL,
    table_id        BIGINT,
    order_number    VARCHAR(50) NOT NULL,
    order_type      VARCHAR(20) NOT NULL DEFAULT 'DINE_IN',
    status          VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    subtotal        NUMERIC(10,2) NOT NULL DEFAULT 0,
    total           NUMERIC(10,2) NOT NULL DEFAULT 0,
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by      BIGINT,
    updated_by      BIGINT,

    CONSTRAINT fk_order_table__restaurant FOREIGN KEY (restaurant_id) REFERENCES restaurant(id),
    CONSTRAINT fk_order_table__waiter FOREIGN KEY (waiter_id) REFERENCES app_user(id),
    CONSTRAINT fk_order_table__table FOREIGN KEY (table_id) REFERENCES restaurant_table(id),
    CONSTRAINT ck_order_table__number_not_blank CHECK (length(trim(order_number)) > 0),
    CONSTRAINT ck_order_table__status CHECK (status IN ('PENDING', 'IN_PREPARATION', 'READY', 'DELIVERED', 'PAID', 'CANCELLED')),
    CONSTRAINT ck_order_table__order_type CHECK (order_type IN ('DINE_IN', 'TAKE_AWAY', 'DELIVERY')),
    CONSTRAINT ck_order_table__subtotal_positive CHECK (subtotal >= 0),
    CONSTRAINT ck_order_table__total_positive CHECK (total >= 0),
    CONSTRAINT uk_order_table__restaurant_number UNIQUE (restaurant_id, order_number)
);

CREATE INDEX idx_order_table__restaurant_id ON order_table (restaurant_id);
CREATE INDEX idx_order_table__waiter_id ON order_table (waiter_id);
CREATE INDEX idx_order_table__table_id ON order_table (table_id);
CREATE INDEX idx_order_table__status ON order_table (status);
CREATE INDEX idx_order_table__created_at ON order_table (created_at);
COMMENT ON TABLE order_table IS 'Orders - renamed from "order" to avoid SQL keyword conflict';

