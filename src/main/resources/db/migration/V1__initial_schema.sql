-- ============================================
-- RESTAURANT PLATFORM - INITIAL SCHEMA
-- ============================================
-- Multi-restaurant platform with master catalog architecture
-- Version: 1.0.0 - Consolidated schema

-- ============================================
-- ORGANIZATION & RESTAURANTS
-- ============================================

CREATE TABLE organization (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(250) NOT NULL,
    company_name    VARCHAR(250) NOT NULL,
    ruc             VARCHAR(20),
    phone           VARCHAR(30),
    email           VARCHAR(120),
    address         TEXT,
    active          BOOLEAN NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by      BIGINT,
    updated_by      BIGINT,

    CONSTRAINT ck_organization__name_not_blank CHECK (length(trim(name)) > 0),
    CONSTRAINT ck_organization__company_name_not_blank CHECK (length(trim(company_name)) > 0)
);

CREATE UNIQUE INDEX uk_organization__ruc ON organization (ruc) WHERE ruc IS NOT NULL;
COMMENT ON TABLE organization IS 'Organizations (empresas) - top level entity';

CREATE TABLE restaurant (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    name            VARCHAR(250) NOT NULL,
    company_name    VARCHAR(250),
    ruc             VARCHAR(20),
    phone           VARCHAR(30),
    email           VARCHAR(120),
    address         TEXT,
    active          BOOLEAN NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by      BIGINT,
    updated_by      BIGINT,

    CONSTRAINT fk_restaurant__organization FOREIGN KEY (organization_id) REFERENCES organization(id),
    CONSTRAINT ck_restaurant__name_not_blank CHECK (length(trim(name)) > 0)
);

CREATE INDEX idx_restaurant__organization_id ON restaurant (organization_id);
CREATE UNIQUE INDEX uk_restaurant__organization_name ON restaurant (organization_id, name);
COMMENT ON TABLE restaurant IS 'Restaurants (sedes) - multiple per organization';

-- ============================================
-- USERS & ACCESS CONTROL
-- ============================================

CREATE TABLE app_user (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    username        VARCHAR(50) NOT NULL,
    password        VARCHAR(255) NOT NULL,
    first_name      VARCHAR(50) NOT NULL,
    last_name       VARCHAR(50) NOT NULL,
    email           VARCHAR(120),
    phone           VARCHAR(30),
    role            VARCHAR(20) NOT NULL,
    enabled         BOOLEAN NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by      BIGINT,
    updated_by      BIGINT,

    CONSTRAINT fk_app_user__organization FOREIGN KEY (organization_id) REFERENCES organization(id),
    CONSTRAINT ck_app_user__username_not_blank CHECK (length(trim(username)) > 0),
    CONSTRAINT ck_app_user__first_name_not_blank CHECK (length(trim(first_name)) > 0),
    CONSTRAINT ck_app_user__last_name_not_blank CHECK (length(trim(last_name)) > 0)
);

CREATE INDEX idx_app_user__organization_id ON app_user (organization_id);
CREATE UNIQUE INDEX uk_app_user__organization_username ON app_user (organization_id, username);
COMMENT ON TABLE app_user IS 'Users - belong to organization, can access multiple restaurants';

CREATE TABLE user_restaurant_access (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL,
    restaurant_id   BIGINT NOT NULL,
    role            VARCHAR(20) NOT NULL,
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by      BIGINT,
    updated_by      BIGINT,

    CONSTRAINT fk_user_restaurant_access__app_user FOREIGN KEY (user_id) REFERENCES app_user(id) ON DELETE CASCADE,
    CONSTRAINT fk_user_restaurant_access__restaurant FOREIGN KEY (restaurant_id) REFERENCES restaurant(id) ON DELETE CASCADE,
    CONSTRAINT ck_user_restaurant_access__role CHECK (role IN ('ADMIN', 'WAITER', 'CASHIER', 'KITCHEN')),
    CONSTRAINT uk_user_restaurant_access__user_restaurant UNIQUE (user_id, restaurant_id)
);

CREATE INDEX idx_user_restaurant_access__user_id ON user_restaurant_access (user_id);
CREATE INDEX idx_user_restaurant_access__restaurant_id ON user_restaurant_access (restaurant_id);
COMMENT ON TABLE user_restaurant_access IS 'User access to restaurants with roles';

-- ============================================
-- MASTER CATALOG (ORGANIZATION-LEVEL)
