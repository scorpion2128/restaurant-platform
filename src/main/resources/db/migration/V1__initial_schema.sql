CREATE TABLE master_product_category (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    name            VARCHAR(80) NOT NULL,
    description     TEXT,
    display_order   INTEGER DEFAULT 0,
    active          BOOLEAN NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by      BIGINT,
    updated_by      BIGINT,

    CONSTRAINT fk_master_product_category__organization FOREIGN KEY (organization_id) REFERENCES organization(id),
    CONSTRAINT ck_master_product_category__name_not_blank CHECK (length(trim(name)) > 0),
    CONSTRAINT uk_master_product_category__organization_name UNIQUE (organization_id, name)
);

CREATE INDEX idx_master_product_category__organization_id ON master_product_category (organization_id);
CREATE INDEX idx_master_product_category__display_order ON master_product_category (display_order);
COMMENT ON TABLE master_product_category IS 'Master product categories - single source of truth for organization';

CREATE TABLE master_product (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id     BIGINT NOT NULL,
    master_category_id  BIGINT NOT NULL,
    code                VARCHAR(50),
    name                VARCHAR(150) NOT NULL,
    description         TEXT,
    base_price          NUMERIC(10,2) NOT NULL,
    active              BOOLEAN NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by          BIGINT,
    updated_by          BIGINT,

    CONSTRAINT fk_master_product__organization FOREIGN KEY (organization_id) REFERENCES organization(id),
    CONSTRAINT fk_master_product__master_category FOREIGN KEY (master_category_id) REFERENCES master_product_category(id),
    CONSTRAINT ck_master_product__name_not_blank CHECK (length(trim(name)) > 0),
    CONSTRAINT ck_master_product__base_price_positive CHECK (base_price >= 0),
    CONSTRAINT uk_master_product__organization_name UNIQUE (organization_id, name)
);

CREATE INDEX idx_master_product__organization_id ON master_product (organization_id);
CREATE INDEX idx_master_product__master_category_id ON master_product (master_category_id);
CREATE UNIQUE INDEX uk_master_product__organization_code ON master_product (organization_id, code) WHERE code IS NOT NULL;
COMMENT ON TABLE master_product IS 'Master products - single source of truth (name, description, base_price)';

CREATE TABLE master_menu_template (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
