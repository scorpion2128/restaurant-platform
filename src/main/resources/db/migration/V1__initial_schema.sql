    name            VARCHAR(120) NOT NULL,
    description     TEXT,
    active          BOOLEAN NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by      BIGINT,
    updated_by      BIGINT,

    CONSTRAINT fk_master_menu_template__organization FOREIGN KEY (organization_id) REFERENCES organization(id),
    CONSTRAINT ck_master_menu_template__name_not_blank CHECK (length(trim(name)) > 0),
    CONSTRAINT uk_master_menu_template__organization_name UNIQUE (organization_id, name)
);

CREATE INDEX idx_master_menu_template__organization_id ON master_menu_template (organization_id);
COMMENT ON TABLE master_menu_template IS 'Master menu templates - shared across organization';

CREATE TABLE master_menu_template_item (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    master_template_id  BIGINT NOT NULL,
    master_product_id   BIGINT NOT NULL,
    display_order       INTEGER DEFAULT 0,
