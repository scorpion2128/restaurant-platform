    CONSTRAINT ck_payment__subtotal_positive CHECK (subtotal >= 0),
    CONSTRAINT ck_payment__igv_positive CHECK (igv_amount >= 0),
    CONSTRAINT ck_payment__total_positive CHECK (total_amount >= 0),
    CONSTRAINT uk_payment__restaurant_number UNIQUE (restaurant_id, payment_number)
);

CREATE INDEX idx_payment__restaurant_id ON payment (restaurant_id);
CREATE INDEX idx_payment__table_id ON payment (table_id);
CREATE INDEX idx_payment__paid_at ON payment (paid_at);
COMMENT ON TABLE payment IS 'Payments for orders';

CREATE TABLE payment_method_detail (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
